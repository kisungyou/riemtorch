test_that("nested products and rigid motions retain explicit factor structure", {
  skip_if_not(torch::torch_is_installed());torch::torch_manual_seed(49)
  M<-manifold.rigidmotion(3);target<-riem.random(M);initial<-riem.random(M)
  P<-riem.problem(M,function(x) ((x$rotation-target$rotation)^2)$sum()/2+((x$translation-target$translation)^2)$sum()/2)
  f0<-scalar(riem.evaluate(P,initial,FALSE)$value)
  fit<-riem.optimize(P,initial,control=list(max_iterations=100))
  expect_lt(fit$objective,f0);expect_true(riem.belongs(M,fit$point))
  nested<-manifold.product(list(motion=M,scale=manifold.euclidean(1)),c(2,3))
  x<-list(motion=initial,scale=tensor(2));u<-list(motion=riemtorch:::.zeros(initial),scale=tensor(1))
  expect_equal(scalar(riem.inner(nested,x,u,u)),3)
  expect_true(riem.belongs(nested,riem.retr(nested,x,u,.1)))
})
test_that("Grassmann projector and frame metrics agree under pushforward", {
  skip_if_not(torch::torch_is_installed());torch::torch_manual_seed(84)
  F<-manifold.grassmann(4,2);M<-manifold.grassmann(4,2,"projection")
  x<-riem.random(F);u<-riem.tangent(F,x,torch::torch_randn_like(x));v<-riem.tangent(F,x,torch::torch_randn_like(x))
  P<-x$matmul(x$t());push<-function(z) z$matmul(x$t())+x$matmul(z$t())
  expect_equal(scalar(riem.inner(F,x,u,v)),scalar(riem.inner(M,P,push(u),push(v))),tolerance=1e-9)
})
test_that("reflection quotient is an explicit Riemann shape variant", {
  skip_if_not(torch::torch_is_installed());torch::torch_manual_seed(79)
  M<-manifold.landmark(5,2,reflections=TRUE);x<-riem.random(M)
  Q<-torch::torch_diag(tensor(c(1,-1)));target<-riem.random(M);P<-riem.problem(M,geom_loss(M,target))
  a<-riem.evaluate(P,x);b<-riem.evaluate(P,x$matmul(Q))
  expect_equal(scalar(a$value),scalar(b$value),tolerance=1e-10)
  expect_lt(normf(b$gradient-a$gradient$matmul(Q)),1e-8)
  fit<-riem.optimize(P,x,control=list(max_iterations=40))
  expect_lt(fit$objective,scalar(a$value));expect_true(riem.belongs(M,fit$point))
})
